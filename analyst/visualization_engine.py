"""
analyst/visualization_engine.py
---------------------------------
Production visualization engine for DIPEX.

Responsibilities:
  - Select the correct chart type based on column types and cardinality
  - Generate structured JSON chart specs for the dashboard renderer
  - Detect misleading visualizations (truncated axis, cherry-picked ranges)
  - Color-blind-safe palettes + auto label/title generation
  - Only reference Gold artefact data — never Bronze/Silver
"""

from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import pandas as pd

logger = logging.getLogger("dipex.visualization")

# ══════════════════════════════════════════════════════════════════════════════
# Color Palettes (WCAG 2.1 color-blind-safe)
# ══════════════════════════════════════════════════════════════════════════════

PALETTE_COLORBLIND_SAFE = [
    "#0072B2",  # blue
    "#E69F00",  # orange
    "#009E73",  # green
    "#CC79A7",  # magenta
    "#56B4E9",  # sky blue
    "#F0E442",  # yellow
    "#D55E00",  # vermillion
    "#000000",  # black
]

CONFIDENCE_COLORS = {
    "verified": "#10b981",
    "retry": "#f59e0b",
    "rejected": "#ef4444",
}

# ══════════════════════════════════════════════════════════════════════════════
# Chart Type Selection Logic
# ══════════════════════════════════════════════════════════════════════════════

def select_chart_type(
    df: pd.DataFrame,
    x_col: str,
    y_col: Optional[str] = None,
    *,
    max_cat_cardinality: int = 20,
) -> str:
    """
    Select the optimal chart type based on column types and cardinality.

    Returns one of: "bar", "line", "scatter", "heatmap", "box", "violin",
                    "histogram", "pie", "area"

    Rules (in priority order):
    1. Time x-axis → line or area
    2. Categorical x, numeric y, cardinality ≤ 20 → bar
    3. Categorical x, cardinality > 20 → box
    4. Numeric x, numeric y, row count ≤ 10K → scatter
    5. Numeric x, numeric y, row count > 10K → heatmap (2D-binned)
    6. Single numeric column → histogram
    7. Categorical with proportion analysis → pie (only if ≤ 6 categories)
    """
    if x_col not in df.columns:
        return "bar"

    x_dtype = df[x_col].dtype
    x_is_time = pd.api.types.is_datetime64_any_dtype(x_dtype)
    x_is_cat = pd.api.types.is_object_dtype(x_dtype) or pd.api.types.is_categorical_dtype(x_dtype)
    x_is_num = pd.api.types.is_numeric_dtype(x_dtype)
    x_card = int(df[x_col].nunique())

    y_is_num = (
        y_col is not None
        and y_col in df.columns
        and pd.api.types.is_numeric_dtype(df[y_col].dtype)
    )
    n_rows = len(df)

    # Priority rule application
    if x_is_time and y_is_num:
        return "line"
    if x_is_time:
        return "area"
    if x_is_cat and y_is_num and x_card <= max_cat_cardinality:
        return "bar"
    if x_is_cat and y_is_num and x_card > max_cat_cardinality:
        return "box"
    if x_is_num and y_is_num and n_rows <= 10_000:
        return "scatter"
    if x_is_num and y_is_num and n_rows > 10_000:
        return "heatmap"
    if x_is_num and y_col is None:
        return "histogram"
    if x_is_cat and y_col is None and x_card <= 6:
        return "pie"
    return "bar"


